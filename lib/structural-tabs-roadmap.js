/**
 * @file Роадмап фазы 3 плана cold open: ленивые вкладки / двухфазный контекст без правок шаблонов системы.
 * Ничего не регистрируется из main.js — это опорный документ для реализации.
 *
 * ## Проблема
 * Handlebars собирает весь лист в одном `_prepareContext` + `_renderHTML`. После вычитания
 * getChatData/enrich основной потолок — объём HTML и проходов по секциям, которые пользователь
 * не видит на первой вкладке.
 *
 * ## Варианты (только модуль dnd4e-lazy-sheet-chatdata)
 *
 * **A. Двухфазный контекст (риск мигания)**
 * - libWrapper `_prepareContext`: первый await — урезанный `context` (например только summary tab +
 *   пустые плейсхолдеры для остальных вкладок); `queueMicrotask` / `requestAnimationFrame` — второй
 *   проход `this.render(false)` или точечное обновление данных через публичный API листа.
 * - Плюс: один проход шаблонов можно оставить частично. Минус: два кадра, нужен анти-flicker (opacity/skeleton).
 *
 * **B. Хуки смены вкладки (меньше мигания, больше интеграции)**
 * - Найти событие dnd4e / ActorSheetV2 при переключении вкладки; при первом показе вкладки —
 *   догрузить данные только для её части контекста и `render(false)`.
 * - Плюс: UX ближе к нативному. Минус: зависимость от внутренних имён вкладок/селекторов системы.
 *
 * **C. Апстрим dnd4e (чистый путь к &lt;1 s)**
 * - Разбить шаблоны на partials с ленивой подгрузкой или официальный флаг «рендер только активной вкладки».
 * - См. {@link file:./parallel-prep-upstream-snippet.js} для идей API prep.
 *
 * ## Риски
 * - ProseMirror / редакторы в биографии при отложенном enrich.
 * - Токены, завязанные на полный DOM листа при открытии.
 * - Совместимость с другими модулями, патчущими тот же `_prepareContext`.
 *
 * ## Критерии приёмки (перед включением по умолчанию)
 * - COLD_OPEN_RUNS=5: median sheetOpenMs vs baseline того же мира.
 * - Ручной чеклист: каждая вкладка, раскрытие предмета, power card, сейв поля.
 */

